"""Stage non-content assets, then invoke the pinned Notist Site manifest."""

import argparse
from pathlib import Path
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def stage_assets(root=ROOT):
    target = root / "target"
    target.mkdir(exist_ok=True)
    destination = target / "site-static"
    marker = destination / ".notist-site-assets"
    if destination.exists() and not marker.exists():
        raise RuntimeError(f"refusing to replace unowned asset directory: {destination}")
    with tempfile.TemporaryDirectory(prefix="site-assets-", dir=target) as temporary:
        stage = Path(temporary) / "assets"
        stage.mkdir()
        shutil.copytree(root / "xiv-market-lite", stage / "xiv-market-lite")
        (stage / ".notist-site-assets").write_text("generated by tools/build_site.py\n")
        if destination.exists():
            shutil.rmtree(destination)
        stage.replace(destination)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["build", "serve", "assets"], nargs="?", default="build")
    args, extra = parser.parse_known_args()
    stage_assets()
    if args.command != "assets":
        subprocess.run(["notist", "--config", "Notist.toml", args.command, *extra], cwd=ROOT, check=True)


if __name__ == "__main__":
    main()
